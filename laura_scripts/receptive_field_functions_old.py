# %% Function to use covariance matrix to plot centre surround receptive field structure
def plot_centre_surrounds_old(dataset, qi_limit):
    # Import dependencies
    import numpy as np
    from pathlib import Path
    import matplotlib as mpl
    import matplotlib.pyplot as plt
    from matplotlib_scalebar.scalebar import ScaleBar
    import datashader as ds
    import datashader.transfer_functions as tf
    import xarray as xr
    from colorcet import coolwarm
    from smoothing.gaussian import smooth_ker
    from location.channel_handling import masking_square
    from covariance.filtering import cov_filtering_sum
    from mpl_toolkits.axes_grid1 import make_axes_locatable
    from tqdm import tqdm

    # Load dataset
    root = Path(dataset)
    # Load quality file
    quality = np.load(root / "quality.npy")

    # Find top cells with quality index > 20
    valid_rows_quality = ~np.isnan(quality[:, 0])
    top_cells_idx = np.where(quality[valid_rows_quality, 0] > qi_limit)
    top_cells_idx = np.where(valid_rows_quality)[0][top_cells_idx]
    top_cells = quality[top_cells_idx, 1].astype(int)

    # Define global variables
    cut = 150
    half_cut = cut // 2
    pixel_size = 4  # micrometres

    # Create plotting grid first
    n_cells = len(top_cells)
    n_cols = 8
    n_rows = int(np.ceil(n_cells / n_cols))

    fig, axs = plt.subplots(n_rows, n_cols, figsize=(20, 20))
    axs = np.atleast_2d(axs)

    # %% Loop through cells and plot immediately
    # Load data, do illumination correction, generate extended array to prevent edge effects, calculate covariance matrix for each cell
    for plot_idx, cell_id in enumerate(
        tqdm(top_cells)
    ):  # can use tqdm to wrap for loop to create progress bar. # For the top cells
        ax = axs[plot_idx // n_cols, plot_idx % n_cols]

        # Load data
        sta_path = (
            root / f"cell_{cell_id}/kernel.npy"
        )  # define the file path to the STA
        sta_data = np.load(sta_path)  # load the STA for cell i as sta_data

        ker_sm = smooth_ker(
            sta_data
        )  # smooth the STA for cell i using the smooth_ker function
        original_shape = (
            sta_data.shape
        )  # calculate the variance of the value of each pixel in the STA across time
        T, H, W = original_shape  # extract the dimensions of the original STA

        # Illumination correction
        data_flat = sta_data.reshape(T, H * W).astype(
            float
        )  # flatten the sta data so that it goes from T,H,W to T,H*W (where T is time/frames)

        sum_img = (
            np.sum(data_flat, axis=0) / 100
        )  # calculate the sum brightness of every pixel across time
        median_sum = np.median(sum_img)  # find the median brightness of pixels
        correction = (
            sum_img - median_sum
        )  # calculate the correction required by each pixel to obtain median brightness

        data_flat -= correction  # correct each pixel for each time frame

        sta_data = data_flat.reshape(
            T, H, W
        )  # reshape corrected sta data back to original 3D shape
        del data_flat  # delete to free up space

        # Create extended sta array where you add cut (defined at start as 150 pixels) onto each dimension, and fill all the pixels with the median value of the array.
        sta_ext = np.full(
            (T, H + cut, W + cut), np.median(sta_data), float
        )  # AND convert to float (numbers that can have a decimal point)
        ker_ext = np.full(
            (T, H + cut, W + cut), np.median(ker_sm), float
        )  # Do the same as above but for the smoothed data

        # place the real STA into the centre of the extended sta array created above
        sta_ext[:, half_cut:-half_cut, half_cut:-half_cut] = sta_data
        ker_ext[:, half_cut:-half_cut, half_cut:-half_cut] = ker_sm
        del sta_data, ker_sm  # delete the temporary arrays

        # redefine original arrays with the extended versions
        sta_data = sta_ext
        ker_sm = ker_ext
        del sta_ext, ker_ext  # delete the temporary arrays

        T, Hext, Wext = sta_data.shape  # calculate the shape of the new extended arrays

        # Find the pixel which has the maximum variance across time - this will become the centre of the RF
        _, cY, cX = np.unravel_index(np.argmax(np.var(ker_sm, axis=0)), ker_sm.shape)

        # Bound check (# shift the centre of the STA in case the window is too close to the edge?)
        cY = np.clip(cY, half_cut, Hext - half_cut)
        cX = np.clip(cX, half_cut, Wext - half_cut)

        # Create a square mask of dimensions of the STA, with TRUE values of dimensions cut x cut, centred on cX, cY.
        mask = masking_square(Hext, Wext, (cX, cY), cut, cut)
        subset_flat = sta_data[
            :, mask
        ]  # take subset of the STA that is in the masked region
        subset_flat[subset_flat == 0] = np.median(
            subset_flat
        )  # replace any zero values with median pixel value
        subset = subset_flat.reshape(T, cut, cut)  # reshape into 3D shape
        del subset_flat

        # Use cov_filtering_sum function to calculate covariance matrix of the subset of the STA, and return the important pixels and the cm
        important_pixels, cm = cov_filtering_sum(subset, (cut, cut))
        mpi = np.unravel_index(np.argmax(cm), cm.shape)
        cm_subset = cm[mpi[0], :].reshape(
            cut, cut
        )  # extract all covariance values of most important pixel

        # Plot immediately
        # Plot the sum of covariance matrix for the important pixels
        # Plot the mean as a grid of images
        x = y = np.arange(0, cut)  # Create xarray DataArray
        cm_xarr = xr.DataArray(cm_subset, coords=[("x", x), ("y", y)])
        max_cm = np.max(np.abs(cm_subset))

        # Datashader raster
        cvs = ds.Canvas(plot_width=599, plot_height=599)
        shade = tf.shade(
            cvs.raster(cm_xarr, interpolate="nearest", agg="max"),
            how="linear",
            cmap=coolwarm,
            span=(-max_cm, max_cm),
        )
        img = shade.to_pil()

        ax.imshow(img, origin="lower")

        # Colorbar
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        norm = mpl.colors.Normalize(vmin=-max_cm, vmax=max_cm)
        sm = mpl.cm.ScalarMappable(norm=norm, cmap="coolwarm")
        fig.colorbar(sm, cax=cax, orientation="vertical", ticks=[-max_cm, 0, max_cm])

        # Scalebar + title
        ax.add_artist(ScaleBar(pixel_size, "um", fixed_value=100))
        ax.set_title(f"Cell ID = {int(cell_id)}")

        # Free memory BEFORE next cell
        # del subset, cm, cm_subset, ker_sm, sta_data
        del subset, cm, ker_sm, sta_data
    # Hide empty subplots
    for j in range(plot_idx + 1, n_rows * n_cols):
        axs[j // n_cols, j % n_cols].axis("off")

    fig.suptitle("Spatial receptive fields for cells with qi > 20", fontsize=20, y=0.99)
    fig.tight_layout()
    plt.show()


