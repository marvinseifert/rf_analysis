# %% Function to plot a multipanel figure of each top QI (>20) cell's receptive field, calculated using mean squared error method


def plot_mse_rf_old(dataset, qi_limit):
    # Import dependencies
    import numpy as np
    from pathlib import Path
    import matplotlib.pyplot as plt
    import math

    # Load dataset
    root = Path(dataset)
    # Load quality file
    quality = np.load(root / "quality.npy")

    # Find top cells with quality index > qi limit
    valid_rows_quality = ~np.isnan(quality[:, 0])
    top_cells_idx = np.where(quality[valid_rows_quality, 0] > qi_limit)
    top_cells_idx = np.where(valid_rows_quality)[0][top_cells_idx]
    top_cells = quality[top_cells_idx, 1].astype(int)

    # Choose number of columns and rows in plot
    n_cols = math.ceil(math.sqrt(len(top_cells)))
    n_rows = math.ceil(len(top_cells) / n_cols)
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(20, 20))
    axes = axes.flatten()

    for idx, cell_id in enumerate(top_cells):
        image = np.load(
            root / f"cell_{int(cell_id)}/subset_dev_img.npy"
        )  # Import subset_dev_img.npy for cells with the best QI (cell index) [generated by running the calculate_mse.py]
        # cax = ax[idx].imshow(image, cmap="Greys", vmin = min_value, vmax = max_value) # imshow is used to display data as an image. cmap defines colour scheme
        cax = axes[idx].imshow(image, cmap="Greys", origin="upper")

        # Add 8 µm = 2-pixel scale bar in the top-right corner
        bar_length_px = 2
        x_end = image.shape[1] - 10  # 10 px from right edge
        x_start = x_end - bar_length_px
        y_pos = 10  # 10 px from top
        axes[idx].plot([x_start, x_end], [y_pos, y_pos], color="red", linewidth=3)
        axes[idx].text(
            x_start - 13,
            y_pos + 11,
            "8 µm",
            color="red",
            fontsize=10,
            ha="left",
            va="bottom",
        )  # <-- move text left by increasing this number

        # Set ticks and labels
        axes[idx].set_title(f"Cell {int(cell_id)}")
        axes[idx].set_xticks([0, 50, 100])
        axes[idx].set_yticks([0, 50, 100])
        axes[idx].set_xlabel("pixels")

    fig.suptitle(
        f"Spatial receptive fields for cells with qi >{qi_limit}", fontsize=20, y=0.99
    )
    plt.tight_layout()
    plt.show()


